"""Crust's C translation of the engine's kernels, for the CPU runtime (gpuphys.c).

    python3 runtime/gpk.py OUTDIR [--crust DIR]     writes OUTDIR/gpk_<kernel file>.c

Each kernels/*.rs the runtime uses is translated by Crust (Rust subset -> C); the `assert ... in
gpu.*` header contracts, which only the SPIR-V back end reads, are dropped, and every function
that is not a kernel entry point is made static so the files link together."""
import os
import re
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ENGINE = os.path.dirname(HERE)
KERNEL_FILES = ("grid", "collision_cell_builder", "prowl_world", "prowl_bodies", "prowl_material", "prowl_curves")

_ASSERT = re.compile(r"\s*assert\s+\w+\s+in\s+gpu\.\w+(?:\([^)]*\))?\s*,?")
_ENTRY = re.compile(r"assert\s+(\w+)\s+in\s+gpu\.compute")
_DEF = re.compile(r"^((?:unsigned int|unsigned|int|float|void)\s+\**)(\w+)\(([^)]*)\)\s*(?=assert|\{)", re.M)


def find_crust(crust=None):
    for c in (crust, os.environ.get("CRUST_DIR"), os.path.join(ENGINE, "..", "crust"), os.path.expanduser("~/crust")):
        if c and os.path.exists(os.path.join(c, "shivyc", "crust.py")):
            return os.path.abspath(c)
    raise SystemExit("gpk: Crust not found (pass --crust DIR or set CRUST_DIR)")


def translate_file(name, crust):
    if crust not in sys.path:
        sys.path.insert(0, crust)
    from shivyc import crust as rust
    with open(os.path.join(ENGINE, "kernels", name + ".rs")) as fh:
        c = rust.translate(fh.read())
    entries = set(_ENTRY.findall(c))
    c = _ASSERT.sub("", c)
    helpers = {m.group(2) for m in _DEF.finditer(c)} - entries
    for h in sorted(helpers):
        # the prototype (on the long first line) and the definition
        c = re.sub(r"(?<![\w])((?:unsigned int|unsigned|int|float|void)\s+\**)%s\(" % re.escape(h),
                   r"static \1%s(" % h, c)
    # libm prototypes the translator adds are fine; our runtime defines the gpu intrinsics
    return '#include <math.h>\n' + c, sorted(entries)


def main(argv):
    out = argv[0]
    crust = find_crust(argv[argv.index("--crust") + 1] if "--crust" in argv else None)
    os.makedirs(out, exist_ok=True)
    for name in KERNEL_FILES:
        text, entries = translate_file(name, crust)
        with open(os.path.join(out, "gpk_%s.c" % name), "w") as fh:
            fh.write("/* generated by gpu-physics-engine/runtime/gpk.py from kernels/%s.rs; do not edit */\n" % name)
            fh.write(text)
        print("gpk_%s.c  %s" % (name, ", ".join(entries)))


if __name__ == "__main__":
    main(sys.argv[1:])
